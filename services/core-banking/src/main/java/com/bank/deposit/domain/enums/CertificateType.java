package com.bank.deposit.domain.enums;

/**
 * 거래 증빙의 종류.
 *
 * <p>둘을 나눈 이유는 담는 내용이 다르기 때문이다. 영수증은 <b>내 계좌에서 무슨 일이
 * 있었나</b>(금액·수수료·잔액)를 말하고, 이체확인증은 <b>내가 누구에게 보냈나</b>
 * (받는 은행·계좌·예금주)를 말한다. 받는 쪽에 제출하는 것은 후자다.
 *
 * <p>그래서 이체가 아닌 거래에는 이체확인증을 발급할 수 없다 — 적을 상대가 없다.
 */
public enum CertificateType {

    /** 거래영수증. 모든 거래에 발급할 수 있다. */
    RECEIPT,

    /** 이체확인증. 이체 거래에만 발급할 수 있다. */
    TRANSFER_CONFIRMATION
}
