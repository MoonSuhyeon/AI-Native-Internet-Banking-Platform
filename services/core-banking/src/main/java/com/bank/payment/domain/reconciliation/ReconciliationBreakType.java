package com.bank.payment.domain.reconciliation;

/**
 * 대사 불일치 유형.
 *
 * <p>순서가 곧 심각도다. 위쪽이 돈이 실제로 어긋났을 가능성이 큰 것이고,
 * 아래로 갈수록 "확인은 필요하나 아직 손실은 아닌" 쪽이다. 한꺼번에 수백 건이
 * 나올 수 있으므로 무엇부터 볼지가 정해져 있어야 한다.
 */
public enum ReconciliationBreakType {

    /**
     * 내부에서는 취소(역분개)했는데 외부는 정산 완료.
     *
     * <p><b>가장 위험하다.</b> 고객 장부에서는 되돌렸는데 망에서는 돈이 나갔다.
     * 자행이 그 차액을 떠안은 상태이고, 시간이 지날수록 회수가 어려워진다.
     */
    REVERSED_BUT_SETTLED,

    /**
     * 내부 원장에 청산대기가 있는데 외부 청산 기록이 없다.
     *
     * <p>고객 계좌에서는 출금됐는데 망으로 나가지 않았다는 뜻이다. 수취인은 못 받고
     * 송금인 돈은 빠져 있다. 전송 유실이거나, 외부 기록 INSERT 가 빠진 것이다.
     */
    MISSING_EXTERNAL,

    /**
     * 외부 청산 기록은 있는데 내부 원장에 없다.
     *
     * <p>망은 처리했는데 장부에 안 남았다. 원장이 사실과 다르므로 결산이 틀어진다.
     */
    MISSING_INTERNAL,

    /**
     * 양쪽 다 있는데 금액이 다르다.
     *
     * <p>차액이 어디로 갔는지 설명되지 않는 상태다.
     */
    AMOUNT_MISMATCH,

    /**
     * 영업일이 끝났는데 외부 상태가 아직 확정되지 않았다(REQUESTED·ACK).
     *
     * <p>손실이 확정된 것은 아니지만 <b>미결제가 조용히 늙는 것</b>을 막는 항목이다.
     * 이것이 없으면 응답이 영영 안 온 건이 아무 신호 없이 쌓인다.
     */
    STALE_PENDING
}
