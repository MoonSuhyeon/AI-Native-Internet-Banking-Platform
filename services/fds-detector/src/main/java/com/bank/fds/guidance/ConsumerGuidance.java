package com.bank.fds.guidance;

import java.util.List;

/**
 * 고객에게 보여 줄 안내.
 *
 * <p><b>왜 필요한가.</b> 탐지기는 사람이 읽을 근거를 이미 만들고 있었다
 * ({@code DetectionSignal.detail} — "평소 최대 50만원, 이번 300만원"). 그런데 그
 * 근거는 결제계까지 갔다가 <b>로그로만 남고 버려졌고</b>, 고객이 보는 것은 고정된
 * 한 줄이었다.
 *
 * <pre>
 *   "이상거래로 판단되어 이체가 제한되었습니다. 고객센터로 문의해 주세요."
 * </pre>
 *
 * <p>이 한 줄이 두 가지를 동시에 놓친다.
 *
 * <ul>
 *   <li><b>왜 막혔는지</b> — 근거가 이미 있는데 전달되지 않는다</li>
 *   <li><b>지금 무엇을 해야 하는지</b> — "고객센터로 문의" 는 조치가 아니라 미루기다</li>
 * </ul>
 *
 * <p>보이스피싱 피해자에게 이 공백은 특히 비싸다. 이 순간 필요한 안내는
 * "고객센터로 문의" 가 아니라 <b>"송금 전에 상대방에게 직접 전화해 확인하세요"</b> 다.
 * 막는 것과 알려 주는 것은 다른 일이고, 지금까지 앞의 것만 하고 있었다.
 *
 * <p><b>왜 탐지기가 만드는가.</b> 신호를 아는 쪽이 여기다. 결제계에서 문구를 만들면
 * 신호 코드의 의미가 두 곳에 흩어지고, 새 규칙을 넣을 때 한쪽만 고쳐진다.
 *
 * <p><b>왜 LLM 이 아닌가.</b> 이 값은 <b>돈이 움직이는 경로 안</b>에서 만들어진다.
 * 판정 예산이 수백 ms 라 생성 모델을 부를 자리가 없고, 더 중요하게는 모델이 죽었을 때
 * 안내가 비어서는 안 된다. 차단만 되고 이유가 없는 화면은 지금 상태보다 나쁘다.
 * 그래서 여기서는 <b>규칙으로 확정</b>하고, 연령대에 맞춘 자연어 다듬기는 화면이
 * 조사 에이전트에게 따로 물어 <b>덧입힌다</b>. 늦게 와도, 안 와도 화면은 성립한다.
 *
 * @param headline    왜 멈췄는지 한 줄. 화면 제목이 된다.
 * @param evidence    판단 근거. {@code DetectionSignal.detail} 을 그대로 옮긴다 —
 *                    심사원이 보는 것과 고객이 보는 것이 같아야 나중에 분쟁에서
 *                    설명이 어긋나지 않는다.
 * @param actionSteps 지금 할 일. 신호 종류마다 다르다.
 * @param choices     화면이 제시할 선택지. {@link Choice} 이름을 쓴다.
 */
public record ConsumerGuidance(
        String headline,
        List<String> evidence,
        List<String> actionSteps,
        List<String> choices
) {

    /**
     * 고객이 고를 수 있는 것.
     *
     * <p>문자열로 넘기는 이유는 결제계·프론트가 이 열거형에 컴파일 의존하지 않게 하기
     * 위해서다. 탐지기가 선택지를 하나 늘려도 나머지가 다시 빌드될 필요는 없다.
     */
    public enum Choice {
        /** 추가 인증하고 계속한다. */
        STEP_UP,
        /** 보내지 않는다. */
        CANCEL,
        /** 상담원에게 넘긴다 — 케이스가 열리고 조사 에이전트가 붙는다. */
        CONSULT
    }
}
