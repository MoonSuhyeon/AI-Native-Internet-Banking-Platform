package com.bank.fds.detect;

/**
 * 대응 등급 — 의심 강도에 따른 조치 사다리.
 *
 * <p><b>왜 등급인가.</b> 실무 FDS 는 "잡느냐 마느냐" 이진법이 아니다. 같은 신호라도
 * 강도에 따라 통과·추가인증·지연·수동심사·차단으로 수위가 갈린다.
 * 감독규정이 말하는 4단계(정보수집·분석탐지·<b>대응</b>·모니터링) 중 세 번째다.
 *
 * <p><b>두 계층이 같은 사다리를 쓴다.</b>
 * <ul>
 *   <li><b>사전(인라인)</b> — 승인 전. 이 거래를 막거나 추가인증을 요구할 수 있다.
 *       예산이 수백 ms 라 조회와 가벼운 판정만 한다.</li>
 *   <li><b>사후(준실시간)</b> — 완료 후. 이 거래는 되돌리지 못하므로 같은 등급을
 *       <i>다음 거래에 대한 통제</i>와 <i>사람에게 넘기기</i>로 해석한다.</li>
 * </ul>
 * 등급을 하나로 둔 이유는, 두 계층이 같은 신호에 다른 이름을 붙이면 지표를 합쳐
 * 볼 수 없고 "사전이 놓친 걸 사후가 잡았는가"를 비교할 수 없기 때문이다.
 *
 * <p><b>실행하지 않는 것이 하나 있다.</b> 지급정지는 권고까지다. 법적 효과가 큰 조치라
 * 사람이 RBAC 아래 발동한다 — 조사 에이전트의 기존 HITL 원칙과 같다.
 */
public enum ResponseTier {

    /** 이상 없음. 프로파일만 갱신한다. */
    PASS,

    /**
     * 표시만 한다. 단독으로는 약하지만 누적되면 의미가 생기는 신호.
     * 이후 판정에서 가중치로 쓰인다 — 지금 사람을 부르지 않는다.
     */
    MONITOR,

    /**
     * 추가인증을 요구한다.
     *
     * <p>사전이면 이 거래에 승인 토큰을 요구하고, 사후면 같은 고객의 다음 이체에
     * 요구한다. 어느 쪽이든 결제계의 {@code TransferApprovalGate} 가 실행 지점이다.
     */
    STEP_UP,

    /**
     * 지연시킨다.
     *
     * <p>보이스피싱 대응의 지연이체·지연인출과 같은 성격이다. 차단만큼 강하지 않으면서
     * 피해자가 되돌릴 시간을 준다 — 실무에서 자주 쓰이는 중간 수위다.
     */
    DELAY,

    /**
     * 사람이 본다.
     *
     * <p>조사 에이전트가 가설을 세우고 근거를 모아 권고를 만들면 심사원이 결정한다.
     * 그 결정은 채택률 지표가 되고 동시에 <b>모델 학습 레이블</b>이 된다.
     */
    HOLD_REVIEW,

    /**
     * 거래를 거절한다. <b>사전에서만 의미가 있다</b> — 끝난 거래는 거절할 수 없다.
     *
     * <p>사후 탐지가 이 등급에 도달하면 {@link #FREEZE_RECOMMEND} 로 올린다.
     */
    BLOCK,

    /**
     * 조사에 넘기고 <b>지급정지를 권고</b>한다. 실행은 사람이 한다.
     */
    FREEZE_RECOMMEND;

    /**
     * 둘 중 강한 쪽.
     *
     * <p>선언 순서가 곧 강도다(PASS &rarr; FREEZE_RECOMMEND). 순서를 바꾸면 이 비교가
     * 조용히 틀리므로, 상수를 끼워 넣을 때는 위치를 지켜야 한다.
     */
    public ResponseTier strongerOf(ResponseTier other) {
        return this.compareTo(other) >= 0 ? this : other;
    }

    /** 사람 손이 필요한 등급인가. 조사 투입 여부를 가른다. */
    public boolean requiresHumanReview() {
        return this == HOLD_REVIEW || this == BLOCK || this == FREEZE_RECOMMEND;
    }

    /**
     * 사후 탐지에서 실제로 취할 수 있는 등급으로 낮춘다(또는 옮긴다).
     *
     * <p>끝난 거래는 막을 수 없다. BLOCK 이 나오면 조용히 통과시키는 게 아니라
     * 지급정지 권고로 <b>올려서</b> 사람에게 보낸다 — 사전이었다면 막았을 거래이므로
     * 사후에 더 약하게 대응하면 안 된다.
     */
    public ResponseTier forPostHoc() {
        return this == BLOCK ? FREEZE_RECOMMEND : this;
    }
}
