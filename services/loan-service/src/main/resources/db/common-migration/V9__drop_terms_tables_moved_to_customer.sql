-- 약관·동의 표를 common_db 에서 뺀다 — 정본이 고객 도메인으로 갔다.
--
-- ## 왜 옮겼나
--
-- 동의는 **고객에 대한 사실**이다. 고객 신원과 상태를 아는 곳이 그것을 지켜야 한다.
-- 여기 있는 동안은 고객번호에 FK 를 걸 수 없어(타 서비스 소유) 값 참조였고, 없는
-- 고객의 동의도 들어갈 수 있었다. customer_db 로 가면서 그 FK 가 실제로 선다.
--
-- ## 왜 남겨 두지 않나
--
-- 같은 개념의 표가 두 곳에 있으면 어느 쪽이 정본인지 나중에 아무도 모른다. 한쪽에만
-- 쓰기 시작하면 다른 쪽은 조용히 낡고, 그 상태로 조회하면 "동의한 적 없다" 는 답이
-- 나온다. 장부가 둘인 것보다 나쁘다.
--
-- ## 옮길 데이터가 없다
--
-- 두 표 모두 **행이 없었다**(템플릿 0건·동의 0건). 읽거나 쓰는 코드도 없었다 —
-- 자바 엔티티도, 리포지토리도, 참조하는 서비스도 없다. 스키마만 서 있었다.
-- 그래서 이관이 아니라 삭제다. 데이터가 있었다면 옮긴 뒤 지우는 마이그레이션이
-- 따로 필요했을 것이다.
--
-- ## 새 자리
--
-- customer-service `V42__terms_consent.sql` — terms_template · terms_consent.
-- 거기서는 삭제가 막혀 있고(트리거), 철회 컬럼만 고칠 수 있다.

-- 순서가 중요하다. consent 가 template 을 참조하므로 자식부터 지운다.
DROP TABLE IF EXISTS common_terms_consent;
DROP TABLE IF EXISTS common_terms_template;
