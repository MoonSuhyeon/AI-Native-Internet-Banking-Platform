package com.bank.harness.validation;

/**
 * 인용된 근거가 실제로 있는지 답하는 인덱스.
 *
 * <p>하네스는 근거의 <b>내용</b>을 모른다. 대출 정책서든 사기 시나리오든 상담 FAQ 든,
 * id 로 실존을 물을 수 있으면 그것으로 충분하다. 내용을 아는 것은 도메인의 구현체다.
 *
 * <p>인터페이스가 메서드 하나뿐인 것은 덜 만든 것이 아니라 경계다.
 * 여기에 "본문을 가져온다"를 넣는 순간 근거의 표현 형식이 하네스로 들어오고,
 * 도메인마다 다른 그 형식이 결국 분기로 돌아온다.
 */
public interface CitationIndex {

    /** id 가 인덱스에 존재하는지. */
    boolean exists(String id);
}
