/**
 * 이 빌드가 함께 배포되는 백엔드 서비스 목록.
 *
 * ## 왜 필요한가
 *
 * 프런트는 은행 전체를 그린다. 그런데 해커톤 제출용 데모 스택은 **영상과 심사
 * 경로가 지나는 서비스만** 올린다(`infra/docker/docker-compose.demo.yml`).
 * 그러면 화면에는 메뉴가 있는데 뒤에 서비스가 없는 자리가 생긴다.
 *
 * 이 상태가 나쁜 이유는 "기능이 없다" 가 아니라 **"눌렀는데 깨진다"** 이기 때문이다.
 * 처음 온 사람은 메뉴를 눌러 보고, 오류를 두어 번 만나면 서비스 전체가 고장 난
 * 것으로 판단한다. 없는 기능은 없는 채로 두는 편이 낫다.
 *
 * ## 왜 환경변수가 아닌가
 *
 * `NEXT_PUBLIC_*` 은 **빌드 시점에 번들에 박히므로** 환경별로 다르게 하려면 빌드
 * 인자를 늘려야 한다. `web/Dockerfile` 은 그 인자를 열 개에서 정리해 없앤 이력이
 * 있다 — 서비스 직통 주소를 인자로 되살릴 수 있는 구멍이었기 때문이다.
 * 제출을 앞두고 그 구조를 다시 늘리지 않는다.
 *
 * 그래서 커밋된 상수 하나로 둔다. 이 파일이 곧 "무엇을 올렸는가" 의 기록이다.
 *
 * ## 되돌리는 법
 *
 * 해당 서비스를 다시 배포하면 아래 값을 `true` 로 바꾼다. 그 한 줄로 메뉴가
 * 돌아온다 — 화면 코드는 지우지 않았다.
 */
export const DEPLOYED = {
  /** customer-service — 인증·고객·직원 신원. 로그인이 여기서 난다. */
  customer: true,

  /** core-banking — 수신·이체. 계좌조회와 이체 화면이 여기에 걸린다. */
  coreBanking: true,

  /** fds-detector + fraud-agent — 이상거래 사전점검과 조사 에이전트. */
  fraud: true,

  /**
   * loan-service — 여신.
   *
   * 데모 스택에서 뺐다. 혼자 오지 않기 때문이다: `loan-db`·`ai-db`·
   * `schema-registry` 가 모두 healthy 해야 뜨고, 상한을 더하면 2.1GB 다.
   * 지금 스택이 5.8GB 라 8GB 서버에서 넘친다. 'AI 대출 심사' 가 실제로 돌려면
   * `auto-loan-review` 와 `review-ai-gateway` 까지 필요해 더 커진다.
   */
  loan: false,

  /**
   * consultation-service — AI 상담 챗봇(상품추천·지출분석·만기관리).
   *
   * 데모 스택에서 뺐다. 챗봇 위젯과 퀵메뉴의 `ask` 항목이 전부 이 서비스를
   * 부르므로, 없으면 열리기만 하고 답이 오지 않는다.
   */
  consultation: false,

  /**
   * Prometheus + Grafana — 관측.
   *
   * 데모 스택에서 뺐다. 어드민의 모니터링 대시보드가 Grafana 를 부르므로,
   * 없으면 화면은 열리는데 목록이 비거나 오류가 난다.
   */
  monitoring: false,
} as const
